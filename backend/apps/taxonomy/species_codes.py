"""Deterministic, institution-scoped Species code allocation.

A Species code is the three-letter prefix of AAA-BBB-X Strain codes and of the
Box codes derived from them. It is generated by the server from the scientific
name only; WoRMS and the client never choose it.

Candidate order for a name "Genus epithet" (letters g1..gm and e1..en):

1. g1 e1 e2                     Aurelia aurita -> AAU
2. g1 e1 ek   (k = 3..n)        AAR, AAI, AAT
3. g1 gj e1   (j = 2..m)        AUA, ARA, AEA, ...
4. g1 ei ek   (2 <= i < k)      ARI, ART, ...
5. g1 gi gk   (2 <= i < k)      AUR, AUE, ...

A name without a specific epithet ("Aurelia", "Aurelia sp.", "Aurelia sp. 2")
uses step 5 only. Qualifiers (sp., cf., aff., var., ...) and hybrid markers
are never read as an epithet; nothing else is inferred from the name.

A candidate is skipped when it is unsafe:

- already assigned to another Species in the active institution;
- already assigned to another Species by any institution, or used as the
  prefix of an existing Strain or Box code of another Species. This is the
  automatic generator's conservative selection rule, not global AAA ownership:
  the legacy assignment API permits cross-institution reuse. Box namespaces
  remain keyed by the full Strain code, with globally unique Box codes.

For an existing Species, a single canonical prefix already carried by its
Strains in the active institution is reused first, so that historical
identifiers stay consistent; several different prefixes are a conflict that
needs a human decision.
"""

import re
import unicodedata

from django.db import IntegrityError, transaction

from apps.cultures.box_identity import CANONICAL_STRAIN_CODE
from apps.cultures.models import Box
from apps.organizations.models import Organization

from .models import OrganizationSpeciesCode, Strain

# Open-name labels: no specific epithet follows ("Aurelia sp. 2").
OPEN_NAME_LABELS = {"sp", "spp", "indet", "ined", "gen", "nov"}
# Comparison qualifiers precede the epithet they refer to ("Aurelia cf. aurita").
EPITHET_QUALIFIERS = {"cf", "aff", "nr"}
HYBRID_MARKERS = {"×", "x", "X"}


class SpeciesCodeError(Exception):
    """No safe code can be assigned; ``code`` is a stable client-facing reason."""

    def __init__(self, code):
        super().__init__(code)
        self.code = code


def _letters(value):
    ascii_value = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^A-Za-z]", "", ascii_value).upper()


def parse_name(scientific_name):
    """Return (genus letters, epithet letters or "") or raise SpeciesCodeError."""
    tokens = scientific_name.replace("×", " × ").split()
    # A leading hybrid marker is ignored; a hybrid formula keeps its first parent.
    while tokens and tokens[0] in HYBRID_MARKERS:
        tokens.pop(0)
    for index, token in enumerate(tokens):
        if token in HYBRID_MARKERS:
            tokens = tokens[:index]
            break
    if not tokens or not tokens[0][0].isalpha():
        raise SpeciesCodeError("name_not_derivable")
    genus = _letters(tokens[0])
    if not genus:
        raise SpeciesCodeError("name_not_derivable")
    epithet = ""
    for token in tokens[1:]:
        label = token.strip(".").lower()
        if token.startswith("(") or label in EPITHET_QUALIFIERS:
            continue
        if label not in OPEN_NAME_LABELS and token.isalpha() and token.islower():
            epithet = _letters(token)
        break
    return genus, epithet


def candidate_codes(scientific_name):
    """All name-derived candidates in the documented order, without duplicates."""
    genus, epithet = parse_name(scientific_name)
    g1, g_rest, e = genus[0], genus[1:], epithet
    ordered = []
    if e:
        ordered += [g1 + e[0] + e[1]] if len(e) > 1 else []
        ordered += [g1 + e[0] + letter for letter in e[2:]]
        ordered += [g1 + letter + e[0] for letter in g_rest]
        ordered += [g1 + e[i] + e[k] for i in range(1, len(e)) for k in range(i + 1, len(e))]
    ordered += [g1 + g_rest[i] + g_rest[k] for i in range(len(g_rest)) for k in range(i + 1, len(g_rest))]
    seen = set()
    return [code for code in ordered if len(code) == 3 and not (code in seen or seen.add(code))]


def _historical_prefixes(organization, species):
    codes = Strain.objects.filter(organization=organization, species=species).values_list("code", flat=True)
    prefixes = set()
    for code in codes:
        match = CANONICAL_STRAIN_CODE.fullmatch(code or "")
        if match:
            prefixes.add(match.group(1))
    return prefixes


def _is_safe(code, organization, species):
    if OrganizationSpeciesCode.objects.filter(code=code).exclude(species=species).exists():
        return False
    prefix = f"{code}-"
    if Strain.objects.filter(code__startswith=prefix).exclude(species=species).exists():
        return False
    return not Box.objects.filter(global_code__startswith=prefix).exclude(strain__species=species).exists()


def lock_species_code_allocation():
    """Serialize automatic selection across institutions until transaction end.

    Call before Organization locks or new Species inserts. No Box namespace or
    Strain locks are taken. This gate does not change legacy manual AAA policy.
    """
    connection = transaction.get_connection()
    if not connection.in_atomic_block:
        raise RuntimeError("Species code allocation requires an atomic transaction.")
    if connection.vendor == "postgresql":
        with connection.cursor() as cursor:
            # Stable application-specific advisory key, separate from row locks.
            cursor.execute("SELECT pg_advisory_xact_lock(%s, %s)", [1347374169, 1])


def allocate_species_code(*, organization, species, recorded_code=None):
    """Return (assignment, created) for the active institution and Species.

    Must run inside the caller's transaction, after authorization. The global
    automatic-allocation gate precedes the institution row lock. Callers that
    insert Species must acquire the gate before that insert, not afterward.
    Local uniqueness constraints remain unchanged. ``recorded_code`` is only for
    trusted callers that verified current institutional evidence under the gates;
    it preserves that exact AAA or fails, never substitutes a generated code.
    """
    lock_species_code_allocation()
    Organization.objects.select_for_update().get(pk=organization.pk)

    existing = OrganizationSpeciesCode.objects.filter(organization=organization, species=species).first()
    if existing is not None:
        return existing, False

    historical = _historical_prefixes(organization, species)
    if recorded_code is not None:
        if re.fullmatch(r"[A-Z]{3}", recorded_code) is None:
            raise SpeciesCodeError("historical_code_conflict")
        historical.add(recorded_code)
    if len(historical) > 1:
        raise SpeciesCodeError("historical_code_conflict")
    generated = candidate_codes(species.scientific_name) if recorded_code is None else []
    if not generated and not historical:
        raise SpeciesCodeError("name_not_derivable")
    candidates = list(historical) + [code for code in generated if code not in historical]

    for code in candidates:
        if not _is_safe(code, organization, species):
            if code in historical:
                raise SpeciesCodeError("historical_code_conflict")
            continue
        try:
            with transaction.atomic():
                assignment = OrganizationSpeciesCode.objects.create(
                    organization=organization, species=species, code=code,
                )
        except IntegrityError:
            # A concurrent writer took this code or assigned this Species.
            existing = OrganizationSpeciesCode.objects.filter(organization=organization, species=species).first()
            if existing is not None:
                return existing, False
            if recorded_code is not None:
                raise SpeciesCodeError("historical_code_conflict") from None
            continue
        return assignment, True
    raise SpeciesCodeError("code_exhausted")
