_CODES = frozenset(ISO_3166_ALPHA2_CODES)


def normalize_country_code(value):
    """Return the canonical alpha-2 code, or None when it is not an assigned code."""
    if not isinstance(value, str):
        return None
    code = value.strip().upper()
    return code if code in _CODES else None
